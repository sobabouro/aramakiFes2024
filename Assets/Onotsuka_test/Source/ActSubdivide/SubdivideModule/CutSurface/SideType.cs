public enum SideType {

    /// <summary>
    /// 図形の y 最大地点
    /// </summary>
    Top,

    /// <summary>
    /// 図形の y 最小地点
    /// </summary>
    Bottom,

    /// <summary>
    /// 図形の y 最大地点と最小地点までを結ぶ二つの境界のうち右側に位置する場合
    /// </summary>
    Right,

    /// <summary>
    /// 図形の y 最大地点と最小地点までを結ぶ二つの境界のうち左側に位置する場合
    /// </summary>
    Left
}
